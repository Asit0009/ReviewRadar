"""Write reports/topic_report.md from the saved topic model, the review tags and the experiment results.

    python -m reviewpulse.nlp.topic_report

Every number and example review in the report is read from saved files. Only the short notes in TOPIC_NOTES are
written by a person, and they describe what was seen when the reviews of each topic were read.
"""

import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional

import pandas as pd

from reviewpulse.config import DATA_PROCESSED_DIR, NLP_DIR, REPORTS_DIR

logger = logging.getLogger(__name__)
REPORT_PATH = REPORTS_DIR / "topic_report.md"
EXPERIMENTS_PATH = REPORTS_DIR / "topic_experiments.json"

# What a person noticed when reading the real reviews of these topics. Keyed by the reviewed name.
TOPIC_NOTES: Dict[str, str] = {
    "General use and results (mixed products)": (
        "A catch-all. Its reviews are about very different products (a solar panel, pencils, a calming supplement, "
        "cleaning wipes, an oil) and mostly say how long something was used or how it worked. It exists because many "
        "reviews have no strong product or aspect word, so NMF groups the leftover general words together. It is large "
        "because that is what the reviews look like, not because it describes one subject."
    ),
    "Age and years (\"5 year old\", \"a year\")": (
        "Mixes two uses of the word 'year': a child's age (\"my 3 year old loves it\") and time (\"broke after one year\")."
    ),
    "Quality (good or poor)": "Contains both praise (\"very good quality\") and complaints (\"poor quality\"); read the sentiment split.",
    "Worth the money or a waste": "Almost half of its reviews are negative: \"waste of money\" sits next to \"worth every penny\".",
    "Perfect size and fit": "Almost all positive. Many are very short reviews such as \"Perfect!\".",
    "Price and value": "Mostly short, positive reviews about the price.",
    "Exactly as described": "Reviews saying the product matched the listing; mostly positive.",
    "Size: too small or too big": "Mostly complaints that an item runs small or is smaller than the photo.",
}


def _excerpt(text: str, limit: int = 150) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= limit else text[:limit].rsplit(" ", 1)[0] + "..."


def _md(text: str) -> str:
    return text.replace("|", "\\|")


def build_report(
    topics_dir: Path = NLP_DIR,
    reviews_path: Path = DATA_PROCESSED_DIR / "reviews_all.parquet",
    experiments_path: Path = EXPERIMENTS_PATH,
) -> str:
    info = json.loads((topics_dir / "topic_labels.json").read_text(encoding="utf-8"))
    tags = pd.read_parquet(topics_dir / "review_topics.parquet")
    reviews = pd.read_parquet(reviews_path, columns=["review_id", "category", "rating", "sentiment", "combined_text"])
    df = tags.merge(reviews, on="review_id")
    tagged, total = len(df), info["total_reviews"]
    p = info["params"]
    topics = sorted(info["topics"], key=lambda t: -t["prevalence_count"])

    out: List[str] = ["# Topic Report", ""]
    out.append("Generated by `python -m reviewpulse.nlp.topic_report` from `artifacts/nmf_topics/`, the processed reviews and `reports/topic_experiments.json`.")
    out += ["", "## 1. What was done", ""]
    out.append(
        f"Topics are found with **TF-IDF + NMF**. TF-IDF turns each review into a list of word weights, where words that are "
        f"common in every review count less. NMF (non-negative matrix factorization) then splits that table into {info['n_topics']} "
        f"topics, each a set of words that tend to appear together, and says how much of each topic every review contains. "
        f"Each review is tagged with the topic it contains most of."
    )
    out += ["", f"- {total:,} reviews, **{tagged:,} tagged** ({tagged / total * 100:.1f}%). The other {total - tagged:,} contain none of the {p['max_features']:,} words and phrases the model knows, so they have no topic.",
            f"- Words and phrases of 1 to 2 words, kept if they appear in at least {p['min_df']} reviews and in at most {int(p['max_df'] * 100)}% of them; the {p['max_features']:,} most frequent are used.",
            f"- Stop words: standard English, plus words that appear in every review (\"product\", \"bought\") and words that only praise (\"excellent\", \"thank\").",
            f"- The topics were learned from the {p['reviews_used_to_fit']:,} reviews with at least {p['min_words_to_fit']} words, then applied to all reviews. Very short reviews carry almost no topic information.",
            "- Percentages below are shares of the tagged reviews, the same way the dashboard reports them.", ""]

    # ----- comparison of settings
    out += ["## 2. Why these settings (comparison of five setups)", ""]
    if experiments_path.exists():
        exp = json.loads(experiments_path.read_text(encoding="utf-8"))
        adopted = next((c for name, c in exp["configs"].items() if "(adopted)" in name), list(exp["configs"].values())[-1])
        out.append(f"Each setup was fitted with {len(exp['seeds'])} random seeds on the same {exp['reviews']:,} reviews; the table shows the mean (and the lowest and highest seed).")
        out += ["", "| Setup | Topics | Biggest topic | Coherence (NPMI, higher is better) | Distinct top words | Weakly assigned reviews |", "| :--- | ---: | ---: | ---: | ---: | ---: |"]
        for name, c in exp["configs"].items():
            b, n, d, w = c["biggest_topic_pct"], c["npmi"], c["distinct_words"], c["weak_pct"]
            out.append(f"| {_md(name)} | {c['topics']} | {b['mean']:.1f}% ({b['min']:.1f}-{b['max']:.1f}) | {n['mean']:+.3f} ({n['min']:+.3f} to {n['max']:+.3f}) | {d['mean']:.2f} | {w['mean']:.1f}% |")
        out += ["", "How to read it:", "",
                "- **Biggest topic** is the share of reviews in the largest topic. A very large value means one topic is a catch-all.",
                "- **Coherence** checks whether a topic's top words really appear together in the same reviews. Differences smaller than the seed-to-seed range are not meaningful.",
                "- **Weakly assigned** reviews have a main topic that holds less than half of their topic weight. Many reviews talk about two things at once (price and size), so some weak assignment is normal and goes up when there are more topics.",
                "- More topics always shrink the biggest topic but spread reviews thinner, so the number of topics was chosen to keep topics readable, not to make the biggest one small.",
                "- Adding more filler words to the stop list made the biggest topic larger, so that idea was rejected.",
                f"- The saved model uses seed 42. Its biggest topic holds {max(t['prevalence_pct'] for t in topics):.1f}% of the tagged reviews; the three seeds in the table gave {adopted['biggest_topic_pct']['min']:.1f}% to {adopted['biggest_topic_pct']['max']:.1f}% for the same settings. So the seed matters, and a single value is approximate.", ""]
    else:
        out += ["(`reports/topic_experiments.json` is missing. Run `python -m reviewpulse.nlp.topic_experiments` to create the comparison.)", ""]

    # ----- topics table
    out += ["## 3. The topics", "",
            "| # | Name | Reviews | Share | Avg rating | Negative | Main categories | Top words |", "| ---: | :--- | ---: | ---: | ---: | ---: | :--- | :--- |"]
    for i, t in enumerate(topics, 1):
        m = df[df["topic_id"] == t["topic_id"]]
        cats = ", ".join(f"{c.replace('_', ' ')} {v * 100:.0f}%" for c, v in m["category"].value_counts(normalize=True).head(2).items())
        out.append(f"| {i} | {_md(t['label'])} | {t['prevalence_count']:,} | {t['prevalence_pct']:.1f}% | {m['rating'].mean():.2f} | {(m['sentiment'] == 'negative').mean() * 100:.0f}% | {cats} | {_md(', '.join(t['top_words'][:6]))} |")
    named = sum(t["named_by"] == "reviewed" for t in topics)
    out += ["", f"{named} of {len(topics)} names were chosen by reading the reviews of each topic. A name is only attached if its key words are among the topic's top words, so a retrained model never reuses a name for a different topic; unmatched topics keep a label made of their top words.", ""]

    # ----- the biggest topic
    big = topics[0]
    mb = df[df["topic_id"] == big["topic_id"]]
    out += ["## 4. The largest topic", "",
            f"**{big['label']}** holds {big['prevalence_count']:,} reviews ({big['prevalence_pct']:.1f}%). Its reviews come from many categories "
            f"({', '.join(f'{c.replace(chr(95), chr(32))} {v * 100:.0f}%' for c, v in mb['category'].value_counts(normalize=True).head(3).items())}), "
            f"its average strongest-topic share is {mb['topic_score'].mean():.2f} (the other topics average {df[df['topic_id'] != big['topic_id']]['topic_score'].mean():.2f}), "
            f"and {(mb['topic_score'] < 0.5).mean() * 100:.0f}% of its reviews are weakly assigned.", ""]
    out.append(TOPIC_NOTES.get(big["label"], ""))
    out += ["", "This was not forced to be smaller. It is the part of the review text that does not fit a clearer theme.", ""]

    # ----- topic by topic
    out += ["## 5. What the reviews in each topic look like", "", "Excerpts are real reviews: the two with the strongest topic score and two random ones (fixed seed).", ""]
    for t in topics:
        m = df[df["topic_id"] == t["topic_id"]]
        out += [f"### {t['label']}", "", f"{t['prevalence_count']:,} reviews, {t['prevalence_pct']:.1f}%. Top words: {', '.join(t['top_words'][:8])}.", ""]
        note: Optional[str] = TOPIC_NOTES.get(t["label"])
        if note and t["topic_id"] != big["topic_id"]:
            out += [f"*Note:* {note}", ""]
        for _, r in m.sort_values("topic_score", ascending=False).head(2).iterrows():
            out.append(f"- strongest, {r['rating']:.0f}★, {r['category'].replace('_', ' ')}: \"{_md(_excerpt(r['combined_text']))}\"")
        for _, r in m.sample(min(2, len(m)), random_state=7).iterrows():
            out.append(f"- random, {r['rating']:.0f}★, {r['category'].replace('_', ' ')}: \"{_md(_excerpt(r['combined_text']))}\"")
        out.append("")

    out += ["## 6. Limitations", "",
            "- NMF finds groups of words that appear together. It does not understand meaning, so a topic can mix two ideas (see the age and years topic).",
            "- A review gets only one topic, although many mention several. The topic score says how dominant it was.",
            "- Several topics are about an aspect that applies to any product (price, quality, size, fit) and not about a kind of product. That is useful for a review dashboard but it means topics overlap with product categories only partly.",
            "- The number of topics is a choice. More topics split themes further but make each less clear.",
            "- Alternatives not tried here: LDA (similar idea, probabilistic), BERTopic (embedding-based, needs more memory and time), and keyword rules.", ""]
    return "\n".join(out)


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
    text = build_report()
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(text, encoding="utf-8")
    logger.info("Wrote %s", REPORT_PATH)


if __name__ == "__main__":
    import argparse

    argparse.ArgumentParser(description="Write reports/topic_report.md from the saved topic model, tags and experiment results.").parse_args()  # no options; this makes --help print help instead of running the job
    main()
