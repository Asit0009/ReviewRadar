"""Write reports/model_evaluation/model_evaluation_report.md from the saved metrics.json.

Every number in the report is copied from metrics.json, which the training scripts write after a real evaluation.
Nothing is typed in by hand, so the report cannot disagree with the dashboard.

    python -m reviewpulse.modeling.report
"""

import json
import logging
from pathlib import Path
from typing import Any, Dict, List

from reviewpulse.config import MODEL_REPORTS_DIR, MODELS_DIR

logger = logging.getLogger(__name__)

NAMES = {"logistic_regression": "TF-IDF + Logistic Regression", "linear_svc": "TF-IDF + Linear SVC", "distilbert": "DistilBERT (fine-tuned)"}
CLASSES = ["negative", "neutral", "positive"]


def _f(v: Any, digits: int = 4) -> str:
    return "n/a" if v is None else f"{v:.{digits}f}"


def _pct(v: Any) -> str:
    return "n/a" if v is None else f"{v * 100:.2f}%"


def build_report(metrics: Dict[str, Any]) -> str:
    models: Dict[str, Any] = metrics.get("models", {})
    split = metrics.get("split_info", {})
    out: List[str] = []
    add = out.append

    add("# Model Evaluation & Sentiment Benchmark Report")
    add("")
    add("*Generated by `python -m reviewpulse.modeling.report` from `artifacts/models/metrics.json`. Every number below is copied from that file, which only the training scripts write after evaluating on held-out reviews.*")
    add("")
    add("**Task:** 3-class sentiment classification of Amazon review text (negative / neutral / positive).  ")
    add("**Labels:** derived from the star rating (1-2 negative, 3 neutral, 4-5 positive). They are a proxy for sentiment, not human annotations. A model that scores well here predicts the star-rating label, which usually, but not always, matches how a person would read the text.")
    add("")
    add("---")
    add("")
    add("## 1. Data split")
    add("")
    add(f"- Reviews in the processed data: **{split.get('source_rows', 'n/a'):,}**")
    add(f"- After removing reviews with identical text: **{split.get('total_deduplicated_samples', 'n/a'):,}**")
    add(f"- Split method: `{split.get('split_strategy', 'n/a')}`")
    add(f"- Reviewers shared between splits: **{split.get('reviewers_shared_between_splits', 'n/a')}**")
    add("")
    add("| Split | Reviews | Share | Reviewers | Negative / Neutral / Positive |")
    add("| :--- | ---: | ---: | ---: | :--- |")
    for label, key, rk, ck in [("Train", "train_samples", "train_reviewers", "class_distribution_train"), ("Validation", "val_samples", "val_reviewers", "class_distribution_val"), ("Test (held out)", "test_samples", "test_reviewers", "class_distribution_test")]:
        dist = split.get(ck) or {}
        total = split.get("total_deduplicated_samples") or 1
        n = split.get(key)
        add(f"| {label} | {n:,} | {n * 100 / total:.1f}% | {split.get(rk, 'n/a'):,} | {dist.get('negative', 'n/a')} / {dist.get('neutral', 'n/a')} / {dist.get('positive', 'n/a')} |" if n is not None else f"| {label} | n/a | n/a | n/a | n/a |")
    add("")
    add("**Why split by reviewer.** People write consistently, so if one reviewer's reviews were spread over train and test the model would be tested on habits it had already seen, and scores would be too high. In the earlier random split, 98% of test reviews came from a reviewer who also had reviews in the training data. Here no reviewer appears in more than one split. The text vectorizer is fitted on the training split only, the regularisation strength C is chosen on the validation split, and the test split is scored once.")
    add("")
    add("---")
    add("")
    add("## 2. Results on the held-out test set")
    add("")
    add("| Model | Accuracy | Macro F1 | Weighted F1 | Negative F1 | Neutral F1 | Positive F1 | Macro precision | Macro recall |")
    add("| :--- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
    for key, m in models.items():
        t = m.get("test", {})
        add(f"| {NAMES.get(key, key)} | {_pct(t.get('accuracy'))} | {_f(t.get('macro_f1'))} | {_f(t.get('weighted_f1'))} | {_f(t.get('negative_f1'))} | {_f(t.get('neutral_f1'))} | {_f(t.get('positive_f1'))} | {_f(t.get('macro_precision'))} | {_f(t.get('macro_recall'))} |")
    add("")
    add("**Reading the numbers.** Most reviews are positive, so a model that always answered \"positive\" would already reach about the positive share as accuracy. Macro F1 (the plain average of the three per-class F1 scores) is the fairer headline, because it does not let the large positive class hide weak performance on negative and neutral reviews. Neutral (3-star) reviews are the hardest: they are rare and their wording overlaps with both other classes.")
    add("")
    add("### Validation results (used to choose hyperparameters)")
    add("")
    add("| Model | Accuracy | Macro F1 | Chosen settings |")
    add("| :--- | ---: | ---: | :--- |")
    for key, m in models.items():
        v = m.get("validation", {})
        hp = m.get("hyperparameters", {})
        chosen = f"C = {hp['C']}, class weights balanced" if "C" in hp else "see training details"
        add(f"| {NAMES.get(key, key)} | {_pct(v.get('accuracy'))} | {_f(v.get('macro_f1'))} | {chosen} |")
    add("")
    add("---")
    add("")
    add("## 3. Confusion matrices (test set)")
    add("")
    add("Rows are the true class, columns the predicted class.")
    for key, m in models.items():
        cm = (m.get("test") or {}).get("confusion_matrix")
        if not cm:
            continue
        add("")
        add(f"**{NAMES.get(key, key)}**")
        add("")
        add("| True \\ Predicted | negative | neutral | positive |")
        add("| :--- | ---: | ---: | ---: |")
        for name, row in zip(CLASSES, cm):
            add(f"| {name} | " + " | ".join(f"{v:,}" for v in row) + " |")
    add("")
    add("---")
    add("")
    add("## 4. DistilBERT")
    add("")
    d = models.get("distilbert")
    if d is None:
        add("**DistilBERT has not been trained.** `metrics.json` contains no DistilBERT result, so none is reported. To train it, run `python -m reviewpulse.modeling.train_distilbert` (see the README for CPU-sized and full-data options).")
    else:
        t = d.get("training", {})
        ev = d.get("evaluated_on", {})
        add(f"Fine-tuned from `{d.get('model_name', 'distilbert-base-uncased')}` and evaluated on **{ev.get('test_samples', 'n/a'):,}** test reviews (the same ones the other models were scored on) and {ev.get('validation_samples', 'n/a'):,} validation reviews.")
        add("")
        add("| Setting | Value |")
        add("| :--- | :--- |")
        for label, key in [("Training reviews used", "train_samples"), ("Size of full training split", "train_split_size"), ("Epochs", "epochs"), ("Batch size", "batch_size"), ("Gradient accumulation steps", "gradient_accumulation_steps"), ("Max tokens per review", "max_length"), ("Learning rate", "learning_rate"), ("Device", "device"), ("Class-weighted loss", "class_weighted_loss"), ("Word embeddings frozen", "frozen_word_embeddings"), ("Mean training loss per epoch", "loss_per_epoch"), ("Training time (seconds)", "training_seconds")]:
            add(f"| {label} | {t.get(key, 'n/a')} |")
        if t.get("train_samples") is not None and t.get("train_split_size") and t["train_samples"] < t["train_split_size"]:
            add("")
            add(f"This was a **subset run**: {t['train_samples']:,} of {t['train_split_size']:,} training reviews, so that it could finish on a CPU with limited memory. Training on the whole split, ideally on a GPU, would probably score higher.")
    add("")
    add("---")
    add("")
    add("## 5. Results by category (test set)")
    add("")
    per_cat = metrics.get("per_category", {})
    if per_cat:
        keys = list(per_cat.keys())
        cats = sorted({c for v in per_cat.values() for c in v})
        add("| Category | Test reviews | " + " | ".join(f"{NAMES.get(k, k)} (acc / macro F1)" for k in keys) + " |")
        add("| :--- | ---: | " + " | ".join("---:" for _ in keys) + " |")
        for c in cats:
            first = per_cat[keys[0]].get(c, {})
            cells = []
            for k in keys:
                r = per_cat[k].get(c)
                cells.append("n/a" if not r else f"{r['accuracy'] * 100:.1f}% / {r['macro_f1']:.3f}{'' if r.get('reliable') else ' ⚠'}")
            add(f"| {c} | {first.get('test_samples', 'n/a')} | " + " | ".join(cells) + " |")
        add("")
        add("⚠ = at least one sentiment class has fewer than 20 test reviews in that category, so the score can swing a lot and should not be compared across categories.")
    else:
        add("No per-category results were saved.")
    add("")
    add("---")
    add("")
    add("## 6. Limitations")
    add("")
    add("- Labels come from star ratings, not from people reading the text.")
    add("- The data is a sample of the first/spread-out parts of very large source files, not a random sample of all Amazon reviews. Scores describe this sample.")
    add("- Per-category scores rest on a few hundred test reviews each, and on only a few dozen negative or neutral ones, so they are noisy.")
    add("- Models were trained once with one random seed; there are no confidence intervals.")
    add("")
    return "\n".join(out)


def write_report(metrics_path: Path = MODELS_DIR / "metrics.json", out_path: Path = MODEL_REPORTS_DIR / "model_evaluation_report.md") -> Path:
    metrics = json.loads(Path(metrics_path).read_text(encoding="utf-8"))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(build_report(metrics), encoding="utf-8")
    logger.info("Wrote %s", out_path)
    return out_path


if __name__ == "__main__":
    import argparse

    argparse.ArgumentParser(description="Write reports/model_evaluation/model_evaluation_report.md from artifacts/models/metrics.json.").parse_args()  # no options; this makes --help print help instead of running the job
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
    print(write_report())
